"""Prompt templates for the Tone Adapter agent."""

from __future__ import annotations

from bot.agents.platform_rules import (
    HUMAN_WRITING_RULES as _HUMAN_WRITING_RULES,
    get_brand_context,
)

TONE_DEFINITIONS = {
    "educational": {
        "label": "Образовательный",
        "instruction": (
            "Перепиши текст в образовательном тоне.\n"
            "Структура: тезис, объяснение, конкретный пример, вывод.\n"
            "Лексика: ясные термины, пояснения в скобках, 'это работает потому что...'.\n"
            "CTA: мягкий, приглашение к изучению: 'Попробуйте и замечайте'.\n"
            "Длина: 600-900 символов."
        ),
    },
    "inspirational": {
        "label": "Вдохновляющий",
        "instruction": (
            "Перепиши текст в вдохновляющем тоне.\n"
            "Структура: образ, эмоциональный резонанс, расширение, приглашение.\n"
            "Лексика: образы, ощущения, 'представьте', метафоры состояния (но живые, не литературные).\n"
            "CTA: приглашение к ощущению: 'Дайте себе минуту прямо сейчас'.\n"
            "Длина: 300-600 символов."
        ),
    },
    "selling": {
        "label": "Продающий",
        "instruction": (
            "Перепиши текст в мягко продающем тоне.\n"
            "Структура: боль/проблема, агитация, решение, social proof, CTA.\n"
            "Лексика: 'результат', 'вы получите', конкретные числа.\n"
            "CTA: прямой но мягкий: 'Напишите в ДМ для записи'.\n"
            "Длина: 400-700 символов."
        ),
    },
    "storytelling": {
        "label": "Сторителлинг",
        "instruction": (
            "Перепиши текст в формате сторителлинга.\n"
            "Структура: завязка (сцена, момент), конфликт/наблюдение, поворот, вывод.\n"
            "Лексика: 'Однажды...', детали сцены, ощущения, внутренний диалог.\n"
            "CTA: через резонанс: 'Было у вас такое?'.\n"
            "Длина: 500-900 символов."
        ),
    },
}


def adapt_tone_prompt(
    text: str,
    tone_key: str,
    topic: str,
    format_key: str,
) -> str:
    tone = TONE_DEFINITIONS.get(tone_key, TONE_DEFINITIONS["educational"])

    return f"""\
{get_brand_context()}
Роль: ты Tone Adapter. Адаптируй тон поста, сохранив все факты и смысл.

Тональность: {tone["label"]}
{tone["instruction"]}

Тема поста: {topic}
Формат: {format_key}

Оригинальный текст:
{text}

{_HUMAN_WRITING_RULES}

КРИТИЧЕСКИ ВАЖНО:
- Сохрани ВСЕ факты, масла, пропорции, свойства из оригинала. Ничего не выдумывай.
- Верни ТОЛЬКО адаптированный текст поста. Без анализа, без комментариев.
- Запрещено markdown-форматирование.
- Если в оригинале есть хэштеги, сохрани их в конце."""
